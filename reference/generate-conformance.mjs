#!/usr/bin/env node
/**
 * generate-conformance.mjs — auto-generate conformance/CONFORMANCE.md
 *
 * Runs the reference verifier over the delegated-authority vectors (ERDL-engine
 * verdict, DESIGN.md §8a) and, on pass, writes a structured conformance report
 * recording: who verified, when, the vector-set version, per-vector attribution
 * (decision + matched_invariant + first_invalid_boundary), the discriminability
 * results (deny-all / allow-all / wrong-attribution), and the attribution-completeness
 * status (Annam §10 attributable rejection).
 *
 * This is the "auto-record" mechanism: the report is produced by the verification
 * run itself, not hand-edited — "Measurements, not endorsements".
 *
 * Usage: node reference/generate-conformance.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Evaluator } from '../../erdl-landing/dist/index.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, '..')
const VECTORS_DIR = resolve(ROOT, 'vectors', 'stateless')
const OUT = resolve(ROOT, 'conformance', 'CONFORMANCE.md')

const evaluator = new Evaluator()

function loadVectors() {
  return readdirSync(VECTORS_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .map((f) => JSON.parse(readFileSync(resolve(VECTORS_DIR, f), 'utf8')))
}

function verdict(vec, context) {
  const r = evaluator.evaluate([vec.rule], context)
  return {
    decision: r.decision,
    matched_invariant: r.matchedRules.length > 0 ? r.matchedRules[0].ruleId.split('_')[0] : null,
  }
}

function main() {
  const vectors = loadVectors()
  const rows = []
  let attackPass = 0
  let legalPass = 0

  for (const vec of vectors) {
    const attack = verdict(vec, vec.attack)
    const legal = evaluator.evaluate([vec.rule], vec.legal)

    const attackOk = attack.decision === 'DENY' && attack.matched_invariant === vec.invariant
    const legalOk = legal.decision === 'ALLOW' && legal.matchedRules.length === 0
    if (attackOk) attackPass++
    if (legalOk) legalPass++

    const att = vec.attribution
    rows.push(
      `| ${vec.id} | ${vec.invariant} | ${attack.decision} | ${attack.matched_invariant} | ${att.violation_hop} | ${att.requested_action} | ${att.effective_authority} | ${attackOk ? '✅' : '❌'} | ${legalOk ? '✅' : '❌'} |`,
    )
  }

  // Discriminability checks (deny-all / allow-all).
  let denyAllConform = 0
  let allowAllConform = 0
  for (const vec of vectors) {
    const exp = verdict(vec, vec.attack)
    if ('DENY' === exp.decision && null === exp.matched_invariant) denyAllConform++
    if ('ALLOW' === exp.decision && null === exp.matched_invariant) allowAllConform++
  }
  const denyAllBlocked = denyAllConform === 0
  const allowAllBlocked = allowAllConform === 0

  const allPass = attackPass === vectors.length && legalPass === vectors.length && denyAllBlocked && allowAllBlocked
  const result = allPass ? 'PASS' : 'FAIL'

  const content = `# ERDL Delegated-Authority Vectors — CONFORMANCE.md

> Auto-generated by the verification run (ERDL-engine verdict, DESIGN.md §8a).
> Runner: OpenOBA reference implementation (Node.js, @openoba/erdl engine).
> Profile: stateless (3-pilot: AV-01 / AV-04 / AV-06). Revocation/freshness vectors are a later stateful profile.

## Verification Results

| Check | Result |
|-------|--------|
| Attack vectors (negative → DENY + correct invariant) | ${attackPass}/${vectors.length} |
| Legal baselines (positive → ALLOW) | ${legalPass}/${vectors.length} |
| deny-all implementation conforms | ${denyAllBlocked ? '0 vectors (blocked ✓)' : 'FAIL'} |
| allow-all implementation conforms | ${allowAllBlocked ? '0 vectors (blocked ✓)' : 'FAIL'} |
| **Result** | **${result}** |

## Per-Vector Attribution

| Vector | Invariant | Decision | Matched invariant | First invalid boundary | Requested action | Effective authority | Attack | Legal |
|--------|-----------|----------|-------------------|------------------------|------------------|---------------------|:------:|:-----:|
${rows.join('\n')}

## Conformance Contract

A runner conforms to a vector iff its output matches, per Annam §10 (attributable rejection)
and his follow-up:

- \`decision\` — engine-derived (DENY / ALLOW)
- \`matched_invariant\` — engine-derived (INV-01 / INV-03 / INV-05)
- \`first_invalid_boundary\` — attribution (the first hop where authority became invalid)
- \`requested_action\` / \`effective_authority\` — attribution (scenario declarations)
- \`reason\` — attribution, **non-normative** (not compared; free text)

A deny-all or allow-all implementation conforms to zero vectors — rejection must be
attributable, not indiscriminate. The legal baseline is the honesty sentinel.

## Methodology

- Verdicts are produced by the ERDL expression engine (erdl-landing), never a hand-written
  authority state machine (DESIGN.md §8a).
- The answer oracle (\`answers.json\`) is a byte-level diagnostic, physically isolated (.gitignore),
  and holds only the engine-derived fields (decision + matched_invariant).
- Level encoding: \`request.level\` / \`authorized.level\` are numeric (L0→0 … L5→5), because
  ERDL's \`gt\` is exact-rational on numbers but lexicographic on strings.
`;

  mkdirSync(resolve(ROOT, 'conformance'), { recursive: true })
  writeFileSync(OUT, content, 'utf8')
  console.log(`CONFORMANCE.md generated (${attackPass}/${vectors.length} attack, ${legalPass}/${vectors.length} legal, result=${result}).`)
  if (!allPass) process.exit(1)
}

main()
